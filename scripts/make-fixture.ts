async function ensureMedia(): Promise<{ png: string; webm: string }> {
  const png = path.join(mediaDir, 'trial-bar.png')
  const webm = path.join(mediaDir, 'upgrade-flow.webm')
  const needPng = !(await exists(png))
  const needWebm = !(await exists(webm))
  if (!needPng && !needWebm) return { png, webm }
  await mkdir(mediaDir, { recursive: true })
  const viewport = { width: 1280, height: 400 }
  const browser = await chromium.launch()
  try {
    if (needPng) {
      console.log('make-fixture: rendering fixtures/media/trial-bar.png')
      const page = await browser.newPage({ viewport })
      await page.setContent(EVIDENCE_PAGE)
      await page.screenshot({ path: png })
      await page.close()
    }
    if (needWebm) {
      console.log('make-fixture: recording fixtures/media/upgrade-flow.webm')
      const videoDir = await mkdtemp(path.join(os.tmpdir(), 'ai-review-video-'))
      const context = await browser.newContext({ viewport, recordVideo: { dir: videoDir, size: viewport } })
      const page = await context.newPage()
      await page.setContent(EVIDENCE_PAGE)
      await page.waitForTimeout(900)
      await page.click('#upgrade')
      await page.waitForTimeout(1200)
      await page.click('#choose-pro')
      await page.waitForTimeout(1300)
      const video = page.video()
      await context.close()
      if (video === null) throw new Error('recordVideo produced no video')
      await video.saveAs(webm)
      await rm(videoDir, { recursive: true, force: true })
    }
  } finally {
    await browser.close()
  }
  return { png, webm }
}

