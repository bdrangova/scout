function generatedFlags(seed: number): string {
  const lines = ['// AUTO-GENERATED by scripts/sync-flags — do not edit by hand.', '// Feature flag registry snapshot.', 'export const FLAGS = {']
  for (let i = 1; i <= 1996; i += 1) {
    const hash = ((Math.imul(i, 2654435761) + seed * 40503) >>> 0).toString(16).padStart(8, '0')
    lines.push(`  flag_${String(i).padStart(4, '0')}: { id: ${i}, hash: '${hash}', enabled: ${(i * seed) % 3 === 0} },`)
  }
  lines.push('} as const', '')
  return lines.join('\n')
}

