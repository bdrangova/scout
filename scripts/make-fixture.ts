  await writeJsonAtomic(path.join(evidence, 'index.json'), EVIDENCE_INDEX)

  const extras = path.join(dir, 'extras')
  await mkdir(extras, { recursive: true })
  for (const item of EXTRAS_INDEX.items) await cp(path.join(inputDir, 'extras', item.file), path.join(extras, item.file))
  await writeJsonAtomic(path.join(extras, 'index.json'), EXTRAS_INDEX)

