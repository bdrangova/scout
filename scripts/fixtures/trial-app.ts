function generatedFlags(seed: number): string {
  const lines = ['// AUTO-GENERATED by scripts/sync-flags — do not edit by hand.', '// Feature flag registry snapshot.', 'export const FLAGS = {']
  for (let i = 1; i <= 1996; i += 1) {
    const hash = ((Math.imul(i, 2654435761) + seed * 40503) >>> 0).toString(16).padStart(8, '0')
    lines.push(`  flag_${String(i).padStart(4, '0')}: { id: ${i}, hash: '${hash}', enabled: ${(i * seed) % 3 === 0} },`)
  }
  lines.push('} as const', '')
  return lines.join('\n')
}

export function lockfile(extraPackages: readonly string[]): string {
  const packages: Record<string, unknown> = {
    '': {
      name: 'trial-app',
      version: '1.0.0',
      dependencies: { react: '^19.0.0', 'react-dom': '^19.0.0' },
      devDependencies: { typescript: '^5.9.0', vitest: '^4.0.0' },
    },
  }
  const names = Array.from({ length: 262 }, (_, i) => `pkg-${String(i + 1).padStart(3, '0')}`)
  for (const name of [...names, ...extraPackages]) {
    const version = `1.${name.length}.${(name.charCodeAt(name.length - 1) * 7) % 10}`
    packages[`node_modules/${name}`] = {
      version,
      resolved: `https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`,
      integrity: `sha512-${Buffer.from(`${name}@${version}`).toString('base64').padEnd(88, 'A')}`,
      license: 'MIT',
    }
  }
  return `${JSON.stringify({ name: 'trial-app', version: '1.0.0', lockfileVersion: 3, requires: true, packages }, null, 2)}\n`
}

