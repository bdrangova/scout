async function initWithOrigin(repo: string, origin: string, files: Record<string, string>, message: string): Promise<void> {
  await mkdir(repo, { recursive: true })
  await git(repo, ['init', '-q', '-b', 'master'])
  await writeFiles(repo, files)
  await git(repo, ['add', '-A'])
  await git(repo, ['commit', '-q', '-m', message])

  await git(reposDir, ['init', '-q', '--bare', origin])
  await git(repo, ['remote', 'add', 'origin', origin])
  await git(repo, ['push', '-q', '-u', 'origin', 'master'])
  await git(repo, ['remote', 'set-head', 'origin', 'master'])
}

/**
 * `trial-app`: one base commit on `master`, pushed to a local bare `trial-app-origin.git` (so
 * `origin/master` resolves), branch `feature/trial-bar` checked out with the whole change set left
 * in the working tree: renames/deletes/adds staged, README.md and Header.tsx modified but
 * unstaged, test/trial-bar.test.ts untracked.
 */
export async function buildTrialRepo(repo: string, origin: string, png: string): Promise<void> {
  await initWithOrigin(repo, origin, BASE_FILES, 'Initial console with free-plan banner')

  await git(repo, ['checkout', '-q', '-b', 'feature/trial-bar'])
  await git(repo, ['mv', 'src/components/Banner.tsx', 'src/components/Notice.tsx'])
  await git(repo, ['rm', '-q', 'src/legacy/OldBanner.ts'])
  await writeFiles(repo, Object.fromEntries(Object.entries(BRANCH_FILES).filter(([rel]) => rel !== 'README.md')))
  await mkdir(path.join(repo, 'src', 'assets'), { recursive: true })
  await cp(png, path.join(repo, 'src', 'assets', 'trial-bar.png'))
  await git(repo, ['add', '-A'])

  // Unstaged edits and one untracked file: the live tree has to pick up all three states.
  await writeFiles(repo, { 'README.md': BRANCH_FILES['README.md']!, 'src/components/Header.tsx': STAGED_ONLY_HEADER })
  await writeFiles(repo, { 'test/trial-bar.test.ts': UNTRACKED_TEST })
}

/** `clean-app`: the trial-app base commit, pushed, with a feature branch checked out and nothing changed. */
export async function buildCleanRepo(repo: string, origin: string, branch: string): Promise<void> {
  await initWithOrigin(repo, origin, BASE_FILES, 'Initial console with free-plan banner')
  await git(repo, ['checkout', '-q', '-b', branch])
}
